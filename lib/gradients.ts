/**
 * Background registry.
 *
 * One entry describes a gradient once. Both the picker swatch and the exported
 * canvas render from the same entry through `gradientToCss`, so a preset cannot
 * look one way in the panel and another way in the export.
 *
 * Linear presets keep their stops as data instead of a baked CSS string so the
 * angle control can re-render them at any direction. Mesh presets are layered
 * radial gradients over a base color and ignore the angle.
 *
 * A background is not always a gradient. A flat colour and no colour at all are
 * the two other things a post needs, and both go through the same
 * `background-image` the gradients do: a solid is written as a one-colour
 * gradient rather than as a `background-color`, so the cross-fade, the grain
 * layer and the export need to know nothing about which kind is showing.
 */

export type GradientFamily =
  | "atmosphere"
  | "aurora"
  | "spectrum"
  | "mono"
  | "defocus"
  | "glow"
  | "horizon"
  | "spectral"
  | "print";

interface Stop {
  color: string;
  /** Position along the axis, in percent. */
  at: number;
}

interface MeshLayer {
  color: string;
  /** Center of the radial layer, in percent of the box. */
  x: number;
  y: number;
  /** Where the layer has faded out completely, in percent. */
  spread: number;
}

interface LinearGradient {
  kind: "linear";
  id: string;
  label: string;
  family: GradientFamily;
  angle: number;
  stops: Stop[];
}

interface MeshGradient {
  kind: "mesh";
  id: string;
  label: string;
  family: GradientFamily;
  base: string;
  layers: MeshLayer[];
}

/**
 * A soft or hard-edged ellipse. `w` and `h` are its radii in percent of the
 * box. `hold` is how far out, in percent of those radii, the colour stays
 * solid before it fades: 0 is a glow, 96 is a shape with a crisp edge, like a
 * dune.
 */
interface BlobLayer {
  shape: "blob";
  color: string;
  x: number;
  y: number;
  w: number;
  h: number;
  hold?: number;
}

/**
 * A circle, for a moon or a sun. Its radius is a percent of the ray to the
 * farthest corner, since CSS takes no percentage for a circle's own size, and
 * that is what keeps it round on a box of any shape.
 */
interface DiscLayer {
  shape: "disc";
  color: string;
  x: number;
  y: number;
  r: number;
  hold?: number;
}

/**
 * A linear layer whose stops may be `transparent`, for a horizon, a wall or
 * an edge. Two stops at nearly one position make a hard line.
 */
interface BandLayer {
  shape: "band";
  angle: number;
  stops: Stop[];
}

export type SceneLayer = BlobLayer | DiscLayer | BandLayer;

/**
 * A picture built from layers over a vertical base: sky over ground, a door
 * onto the sea, a lens glowing in the dark. The base is opaque, top to
 * bottom, so the preset as a whole is opaque whatever the layers leave
 * showing. It ignores the angle, because turning a horizon is not a thing a
 * reader means.
 */
interface SceneGradient {
  kind: "scene";
  id: string;
  label: string;
  family: GradientFamily;
  base: Stop[];
  /** Top first, which is CSS order. */
  layers: SceneLayer[];
}

export type GradientPreset = LinearGradient | MeshGradient | SceneGradient;

